"""Read-only access to the PPT-derived colour palettes (``palettes.json``).

The file is generated by ``scripts/extract_palettes.py`` from the user's
``科研绘图.pptx`` and is treated as read-only data: this module never rewrites
ids or colours.  Renderers resolve three roles:

* ``categorical`` – series colours (lines / bars / scatter groups / point markers)
* ``sequential``  – continuous fills, choropleth classes, default colourbar
* ``diverging``   – signed data, heatmaps centred at zero, positive/negative colourbars

Priority rules live in the chart modules: explicit ``map.colorbar.palette`` >
``style.paletteSequential`` > legacy ``map.colorbar.cmap``.
"""

from __future__ import annotations

import json
import os
from typing import Any, Dict, List, Optional

_HERE = os.path.dirname(os.path.abspath(__file__))
PALETTES_PATH = os.path.join(_HERE, "palettes.json")

_CACHE: Dict[str, Any] = {}


def doc() -> Dict[str, Any]:
    if "doc" not in _CACHE:
        try:
            with open(PALETTES_PATH, "r", encoding="utf-8") as handle:
                _CACHE["doc"] = json.load(handle)
        except Exception:  # noqa: BLE001 - degrade to no palettes
            _CACHE["doc"] = {"palettes": []}
    return _CACHE["doc"]


def all_palettes() -> List[Dict[str, Any]]:
    return list(doc().get("palettes") or [])


def by_kind(kind: str) -> List[Dict[str, Any]]:
    return [palette for palette in all_palettes() if palette.get("kind") == kind]


def by_id(palette_id: str) -> Optional[Dict[str, Any]]:
    if not palette_id:
        return None
    if "index" not in _CACHE:
        _CACHE["index"] = {p.get("id"): p for p in all_palettes()}
    return _CACHE["index"].get(str(palette_id).strip())


def kind_of(palette_id: str) -> str:
    palette = by_id(palette_id)
    return str(palette.get("kind") or "") if palette else ""


def name_of(palette_id: str) -> str:
    palette = by_id(palette_id)
    return str(palette.get("name") or palette_id) if palette else str(palette_id)


def colors_of(palette_id: str) -> List[str]:
    palette = by_id(palette_id)
    if not palette:
        return []
    colors = [str(color) for color in palette.get("colors") or [] if str(color).strip()]
    return colors


def ids(kind: Optional[str] = None) -> List[str]:
    palettes = by_kind(kind) if kind else all_palettes()
    return [str(p.get("id")) for p in palettes if p.get("id")]


def first_id(kind: str) -> str:
    palette_ids = ids(kind)
    return palette_ids[0] if palette_ids else ""


def labels(kind: Optional[str] = None) -> Dict[str, str]:
    palettes = by_kind(kind) if kind else all_palettes()
    return {str(p["id"]): str(p.get("name") or p["id"]) for p in palettes if p.get("id")}


def categorical_colors(palette_id: str, count: int) -> Optional[List[str]]:
    """Cycle one categorical palette's hex colours to *count* entries."""
    colors = colors_of(palette_id)
    if not colors:
        return None
    return [colors[index % len(colors)] for index in range(max(1, count))]


def _linear_cmap(palette_id: str, ctx=None, label: str = "palette"):
    """Build a smooth LinearSegmentedColormap from a stored palette."""
    colors = colors_of(palette_id)
    if not colors:
        return None
    try:
        from matplotlib.colors import LinearSegmentedColormap

        name = "scifig-" + str(palette_id).replace(" ", "_")
        return LinearSegmentedColormap.from_list(name, colors, N=256)
    except Exception:  # noqa: BLE001
        return None


def sequential_cmap(palette_id: str, ctx=None):
    if kind_of(palette_id) in ("sequential", "diverging"):
        return _linear_cmap(palette_id, ctx)
    return None


def diverging_cmap(palette_id: str, ctx=None):
    if kind_of(palette_id) == "diverging":
        return _linear_cmap(palette_id, ctx)
    return None


def class_colors(palette_id: str, count: int) -> Optional[List[str]]:
    """Pick *count* ordered colours from any palette (categorical or band)."""
    colors = colors_of(palette_id)
    if not colors:
        return None
    count = max(1, int(count))
    if count == 1:
        return [colors[-1]]
    if palette_id and kind_of(palette_id) == "categorical":
        if count <= len(colors):
            return colors[:count]
        return [colors[index % len(colors)] for index in range(count)]
    # sequential/diverging bands: sample evenly across the ramp
    if count <= len(colors):
        step = (len(colors) - 1) / float(count - 1)
        return [colors[int(round(index * step))] for index in range(count)]
    return [colors[index % len(colors)] for index in range(count)]


def reset_cache() -> None:
    _CACHE.clear()
